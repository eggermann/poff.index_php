<?php
declare(strict_types=1);

function pageoffRemoteTextConverterHandle(array $payload): array
{
    $source = is_array($payload['source'] ?? null) ? $payload['source'] : [];
    $converter = is_array($payload['converter'] ?? null) ? $payload['converter'] : [];
    $editor = is_array($payload['editor'] ?? null) ? $payload['editor'] : [];
    $target = is_array($payload['target'] ?? null) ? $payload['target'] : [];

    $converterId = strtolower(trim((string) ($converter['id'] ?? '')));
    if ($converterId !== 'converter/convert-pageoff-remote-text') {
        return [
            'ok' => false,
            'error' => 'Unsupported converter for pageoff local PHP endpoint.',
        ];
    }

    $sourcePath = str_replace('\\', '/', trim((string) ($source['path'] ?? ''), '/'));
    $sourceName = (string) ($source['name'] ?? ($sourcePath !== '' ? basename($sourcePath) : 'text-source'));
    $requestedFormat = strtolower(trim((string) ($converter['format'] ?? 'html')));
    $actualFormat = $requestedFormat === 'txt' ? 'txt' : 'html';
    $fontSize = trim((string) ($converter['fontSize'] ?? ($editor['fontSize'] ?? '16px')));
    if ($fontSize === '') {
        $fontSize = '16px';
    }
    $outputName = trim((string) ($target['saveAs'] ?? ''));
    if ($outputName === '') {
        $baseName = pathinfo($sourceName, PATHINFO_FILENAME);
        $outputName = $baseName . '.' . $actualFormat;
    }
    $content = array_key_exists('content', $editor) ? (string) ($editor['content'] ?? '') : '';

    if ($actualFormat === 'txt') {
        $body = "Generated by remote PHP converter\n"
            . "Source: {$sourceName}\n"
            . "Font size: {$fontSize}\n"
            . "PHP used: yes\n\n"
            . $content;
        $mimeType = 'text/plain';
    } else {
        $safeTitle = htmlspecialchars($sourceName, ENT_QUOTES, 'UTF-8');
        $safeFontSize = htmlspecialchars($fontSize, ENT_QUOTES, 'UTF-8');
        $safeBody = htmlspecialchars($content, ENT_QUOTES, 'UTF-8');
        $body = <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{$safeTitle}</title>
    <style>
        body {
            margin: 0;
            font-family: "IBM Plex Sans", "Segoe UI", sans-serif;
            background: #0b1020;
            color: #e6eefc;
        }
        .pageoff-remote-php {
            max-width: 72rem;
            margin: 0 auto;
            padding: 2rem;
        }
        .pageoff-remote-php__meta {
            display: grid;
            gap: 0.5rem;
            margin-bottom: 1.25rem;
            color: #8da7cb;
        }
        .pageoff-remote-php__surface {
            border: 1px solid rgba(124, 162, 255, 0.28);
            border-radius: 1rem;
            background: rgba(14, 22, 42, 0.88);
            box-shadow: 0 24px 80px rgba(0, 0, 0, 0.35);
            overflow: hidden;
        }
        .pageoff-remote-php__content {
            margin: 0;
            padding: 1.5rem;
            font-family: "IBM Plex Mono", "SFMono-Regular", monospace;
            font-size: {$safeFontSize};
            line-height: 1.65;
            white-space: pre-wrap;
            word-break: break-word;
        }
    </style>
</head>
<body>
    <main class="pageoff-remote-php">
        <div class="pageoff-remote-php__meta">
            <strong>Generated by remote PHP converter</strong>
            <span>Source: {$safeTitle}</span>
            <span>Font size: {$safeFontSize}</span>
            <span>PHP used: yes</span>
        </div>
        <section class="pageoff-remote-php__surface">
            <pre class="pageoff-remote-php__content">{$safeBody}</pre>
        </section>
    </main>
</body>
</html>
HTML;
        $mimeType = 'text/html';
    }

    return [
        'ok' => true,
        'type' => 'converted-work',
        'source' => [
            'path' => $sourcePath,
            'mimeType' => (string) ($source['mimeType'] ?? ''),
        ],
        'output' => [
            'name' => $outputName,
            'mimeType' => $mimeType,
            'kind' => 'text',
            'size' => strlen($body),
            'bodyBase64' => base64_encode($body),
        ],
        'generatedBy' => [
            'type' => 'converter',
            'name' => 'convert-pageoff-remote-text',
            'id' => 'converter/convert-pageoff-remote-text',
            'node' => 'pageoff-local-php',
            'engine' => 'remote-node',
            'fontSize' => $fontSize,
            'format' => $actualFormat,
            'usedPhp' => true,
            'convertedAt' => date('c'),
        ],
    ];
}

if (realpath((string) ($_SERVER['SCRIPT_FILENAME'] ?? '')) === __FILE__) {
    $raw = file_get_contents('php://input');
    $payload = $raw !== false && $raw !== '' ? json_decode($raw, true) : [];
    if (!is_array($payload)) {
        $payload = [];
    }

    header('Content-Type: application/json');
    echo json_encode(pageoffRemoteTextConverterHandle($payload), JSON_UNESCAPED_SLASHES);
    exit;
}
